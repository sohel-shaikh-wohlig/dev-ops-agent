"""Basic arithmetic operations with full documentation and tests."""


def add(a: float, b: float) -> float:
    """Return the sum of a and b.

    Args:
        a: First number.
        b: Second number.

    Returns:
        The sum of a and b.
    """
    return a + b


def multiply(a: float, b: float) -> float:
    """Return the product of a and b.

    Args:
        a: First number.
        b: Second number.

    Returns:
        The product of a and b.
    """
    return a * b


def subtract(a: float, b: float) -> float:
    """Return b subtracted from a.

    Args:
        a: First number.
        b: Second number.

    Returns:
        The result of a minus b.
    """
    return a - b
